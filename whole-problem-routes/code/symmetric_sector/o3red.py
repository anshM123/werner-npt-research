"""O(3)-reduction for invariant operators on Sym^n(R^3) (x) Sym^n(R^3).

Coupled basis: for each total spin L, real M=0 vectors w^L_r (r = 1..m_L), and multiplets |L,M,r> generated by ladder
operators.  Invariant operators X = sum_L sum_{rs} X_L[r,s] E^L_{rs}, E^L_{rs} = sum_M |L,M,r><L,M,s|, X_L[r,s] =
<w^L_r|X|w^L_s>.  Gamma (partial transpose on the second factor, real monomial basis) maps invariant operators to
invariant operators; we compute its matrix G in the basis E^L_{rs}.
"""
import numpy as np
from bos import mindices, index_of


def gens_sym(n, d=3):
    """Real antisymmetric rotation generators L_{ij} = a_i^+ a_j - a_j^+ a_i on Sym^n in the orthonormal monomial basis."""
    al = mindices(n, d); idx = index_of(n, d); N = len(al)
    G = {}
    for i in range(d):
        for j in range(d):
            if i == j:
                continue
            M = np.zeros((N, N))
            for c, a in enumerate(al):
                if a[j] > 0:
                    b = list(a); b[j] -= 1; b[i] += 1
                    M[idx[tuple(b)], c] += np.sqrt(a[j] * (a[i] + 1))
            G[i, j] = M
    L = {}
    for i in range(d):
        for j in range(d):
            if i < j:
                L[i, j] = G[i, j] - G[j, i]
    return L


class O3Red:
    def __init__(self, n, tol=1e-8):
        self.n = n
        N = len(mindices(n)); self.N = N
        Lg = gens_sym(n)
        I = np.eye(N)
        # standard: L1 = L_32 (e2->e3), L2 = L_13 (e3->e1), L3 = L_21 (e1->e2); L_ij(e_j) = e_i, L_ij = -L_ji
        L1 = -Lg[1, 2]; L2 = Lg[0, 2]; L3 = -Lg[0, 1]
        self.Lone = (L1, L2, L3)
        J = [np.kron(Lk, I) + np.kron(I, Lk) for Lk in (L1, L2, L3)]
        self.Jreal = J
        C2 = -(J[0] @ J[0] + J[1] @ J[1] + J[2] @ J[2])
        ev, U = np.linalg.eigh(C2)
        Ls = np.round((-1 + np.sqrt(1 + 4 * np.maximum(ev, 0))) / 2).astype(int)
        assert np.allclose(Ls * (Ls + 1), ev, atol=1e-6)
        Jz = 1j * J[2]
        Jp = 1j * J[0] - J[1]  # J_+ = J_1 + i J_2 with J_k = i L_k
        Jm = 1j * J[0] + J[1]
        # check commutator [Jz, Jp] = Jp
        assert np.allclose(Jz @ Jp - Jp @ Jz, Jp, atol=1e-8)
        self.blocks = {}
        for Lval in sorted(set(Ls)):
            UL = U[:, Ls == Lval]
            # M=0 vectors: kernel of J3 (real) within UL
            A = UL.T @ J[2] @ UL
            w, V = np.linalg.eigh(A.T @ A)
            ker = V[:, w < tol]
            W0 = UL @ ker  # real orthonormal columns
            m = W0.shape[1]
            assert m * (2 * Lval + 1) == UL.shape[1], (Lval, m, UL.shape)
            # multiplets
            mult = np.zeros((2 * Lval + 1, N * N, m), complex)  # index M + L
            mult[Lval] = W0
            v = W0.astype(complex)
            for M in range(0, Lval):
                v = Jp @ v / np.sqrt(Lval * (Lval + 1) - M * (M + 1))
                mult[Lval + M + 1] = v
            v = W0.astype(complex)
            for M in range(0, -Lval, -1):
                v = Jm @ v / np.sqrt(Lval * (Lval + 1) - M * (M - 1))
                mult[Lval + M - 1] = v
            self.blocks[Lval] = dict(W0=W0, m=m, mult=mult)
        self.Lvals = sorted(self.blocks)
        self.dim_inv = sum(self.blocks[L]['m'] ** 2 for L in self.Lvals)
        self.labels = [(L, r, s) for L in self.Lvals for r in range(self.blocks[L]['m']) for s in range(self.blocks[L]['m'])]
        self.pos = {lab: i for i, lab in enumerate(self.labels)}

    def E(self, L, r, s):
        mult = self.blocks[L]['mult']
        X = np.einsum('ka,kb->ab', mult[:, :, r], mult[:, :, s].conj())
        assert np.abs(X.imag).max() < 1e-9
        return X.real

    def block(self, X, L):
        W0 = self.blocks[L]['W0']
        return W0.T @ X @ W0

    def gamma_op(self, X):
        N = self.N
        return X.reshape(N, N, N, N).transpose(0, 3, 2, 1).reshape(N * N, N * N)

    def gamma_matrix(self):
        """G[(L',r',s'), (L,r,s)] = <w^{L'}_{r'}| Gamma(E^L_{rs}) |w^{L'}_{s'}>."""
        labels = [(L, r, s) for L in self.Lvals for r in range(self.blocks[L]['m']) for s in range(self.blocks[L]['m'])]
        pos = {lab: i for i, lab in enumerate(labels)}
        Wst = np.concatenate([self.blocks[L]['W0'] for L in self.Lvals], axis=1)
        offs = {}; o = 0
        for L in self.Lvals:
            offs[L] = o; o += self.blocks[L]['m']
        G = np.zeros((len(labels), len(labels)))
        for (L, r, s) in labels:
            GE = self.gamma_op(self.E(L, r, s))
            B = Wst.T @ GE @ Wst
            for Lp in self.Lvals:
                mp = self.blocks[Lp]['m']; o = offs[Lp]
                for rp in range(mp):
                    for sp in range(mp):
                        G[pos[(Lp, rp, sp)], pos[(L, r, s)]] = B[o + rp, o + sp]
        self.labels = labels; self.pos = pos
        return G
