"""Self-similarity test SS_2: is the Choi matrix of P_a (x) P_a (81 x 81 on (in1 in2) (x) (out1 out2)) in the cone
generated by local filterings (A (x) B) C_a (A (x) B)^* of ONE copy C_a (A, B : C^3 -> C^9) plus product operators?
If yes for some a < 1, P_a is tensor-stable positive (induction on blocks of two copies). Least-squares fits with
random restarts; residual = relative Frobenius norm. Controls: a random element of the cone (in-cone floor), and a = 1
(C_1 (x) C_1 is separable, so products alone suffice)."""
import sys, time
import numpy as np, torch
torch.set_default_dtype(torch.float64)
d = 3
F = np.zeros((9, 9)); Om = np.zeros((9, 9))
for i in range(3):
    for j in range(3):
        F[3 * i + j, 3 * j + i] = 1
        Om[3 * i + i, 3 * j + j] = 1
def choi(a):
    return a * np.eye(9) - 0.25 * (F + Om)
def two_copy(C):
    # C on (in, out); C (x) C reordered to (in1 in2) (x) (out1 out2)
    T = np.kron(C, C).reshape([3] * 8)          # indices: in1 out1 in2 out2 | in1' out1' in2' out2'
    T = T.transpose(0, 2, 1, 3, 4, 6, 5, 7)     # in1 in2 out1 out2 | ...
    return T.reshape(81, 81)
def fit(Y, base, nlf, npr, iters, restarts, seed):
    torch.manual_seed(seed)
    R0 = torch.tensor(base, dtype=torch.complex128); Yt = torch.tensor(Y, dtype=torch.complex128)
    best = np.inf
    for r in range(restarts):
        P = [(0.3 * torch.randn(*s, dtype=torch.complex128)).requires_grad_()
             for s in ((nlf, 9, 3), (nlf, 9, 3), (npr, 9), (npr, 9))]
        def model():
            K = torch.einsum('jab,jcd->jacbd', P[0], P[1]).reshape(nlf, 81, 9)
            M = (K @ R0 @ K.conj().transpose(1, 2)).sum(0)
            V = torch.einsum('ka,kb->kab', P[2], P[3]).reshape(npr, 81)
            return M + V.T @ V.conj()
        opt = torch.optim.LBFGS(P, lr=1, max_iter=iters, history_size=50, line_search_fn='strong_wolfe',
                                tolerance_grad=1e-14, tolerance_change=1e-16)
        def closure():
            opt.zero_grad(); loss = torch.linalg.norm(model() - Yt) ** 2; loss.backward(); return loss
        opt.step(closure)
        with torch.no_grad():
            best = min(best, float(torch.linalg.norm(model() - Yt) / torch.linalg.norm(Yt)))
    return best
nlf, npr = int(sys.argv[1]) if len(sys.argv) > 1 else 40, int(sys.argv[2]) if len(sys.argv) > 2 else 120
iters = 3000; t0 = time.time()
rng = np.random.default_rng(1)
# control: a random element of the cone at a = 0.85 (10 filterings + 20 products), same budget
a = 0.85; C = choi(a); M = 0
for _ in range(10):
    A = rng.standard_normal((9, 3)) + 1j * rng.standard_normal((9, 3)); B = rng.standard_normal((9, 3)) + 1j * rng.standard_normal((9, 3))
    K = np.einsum('ab,cd->acbd', A, B).reshape(81, 9)   # (in1 in2, out1 out2) <- (in, out)
    M = M + K @ C @ K.conj().T
for _ in range(20):
    v = np.kron(rng.standard_normal(9) + 1j * rng.standard_normal(9), rng.standard_normal(9) + 1j * rng.standard_normal(9))
    M = M + 0.3 * np.outer(v, v.conj())
print(f'control (random cone element at a = 0.85): residual {fit(M, C, nlf, npr, iters, 2, 0):.2e} [{time.time() - t0:.0f}s]', flush=True)
for a in (1.0, 0.99, 0.95, 0.9, 0.85, 0.75):
    Y = two_copy(choi(a))
    r_lf = fit(Y, choi(a), nlf, npr, iters, 3, 1)
    r_pr = fit(Y, choi(a), 1, npr, iters, 2, 2) if a < 1 else float('nan')
    print(f'a = {a}: C_a (x) C_a residual {r_lf:.2e} with {nlf} filterings + {npr} products; '
          f'(1 filtering + products: {r_pr:.2e}) [{time.time() - t0:.0f}s]', flush=True)
